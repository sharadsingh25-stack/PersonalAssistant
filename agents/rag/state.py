from typing import Any, TypedDict

class AgentState(TypedDict, total=False):

    # ----------------------------------------
    # User input
    # ----------------------------------------

    question: str

    # ----------------------------------------
    # Query routing
    # ----------------------------------------

    category: str | None

    # ----------------------------------------
    # Retrieval
    # ----------------------------------------

    retrieved_documents: list[Any]

    # ----------------------------------------
    # Context
    # ----------------------------------------

    context: str

    # ----------------------------------------
    # Validation
    # ----------------------------------------

    context_found: bool

    # ----------------------------------------
    # Final response
    # ----------------------------------------

    answer: str

    # ----------------------------------------
    # Source information
    # ----------------------------------------

    sources: list[dict[str, Any]]